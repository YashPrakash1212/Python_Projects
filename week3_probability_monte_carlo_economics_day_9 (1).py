import random

def monty_hall_game(switch):
    doors = [1, 2, 3]
    car_door = random.choice(doors)
    player_choice = random.choice(doors)

    # Host opens a door that is neither the car nor the player's choice
    remaining_doors = [d for d in doors if d != player_choice and d != car_door]
    host_opens = random.choice(remaining_doors)

    if switch:
        # Switch to the one remaining unopened door
        final_choice = [d for d in doors if d != player_choice and d != host_opens][0]
    else:
        final_choice = player_choice

    return final_choice == car_door


num_games = 10000

stay_wins = sum(monty_hall_game(switch=False) for _ in range(num_games))
switch_wins = sum(monty_hall_game(switch=True) for _ in range(num_games))

print(f"Strategy: Always Stay   -> Win rate: {stay_wins / num_games * 100:.2f}%")
print(f"Strategy: Always Switch -> Win rate: {switch_wins / num_games * 100:.2f}%")

