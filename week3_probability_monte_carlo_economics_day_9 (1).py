#Excercise 1
import random

def flip_coins(num_flips):
    heads = 0
    tails = 0
    results = []

    for i in range(num_flips):
        flip = random.choice(["Heads", "Tails"])
        results.append(flip)
        if flip == "Heads":
            heads += 1
        else:
            tails += 1

    return results, heads, tails


def run_trial(num_flips):
    results, heads, tails = flip_coins(num_flips)
    print(f"\n--- Flipping {num_flips} times ---")

    # Only print individual results for small numbers of flips
    if num_flips <= 20:
        print("Results:", results)

    print(f"Heads: {heads} ({heads/num_flips*100:.2f}%)")
    print(f"Tails: {tails} ({tails/num_flips*100:.2f}%)")


# Run for 10, 100, and 1000 flips
for n in [10, 100, 1000]:
    run_trial(n)
import random
import matplotlib.pyplot as plt

def simulate_flips(num_flips):
    running_avg = []
    heads_count = 0

    for i in range(1, num_flips + 1):
        flip = random.choice([0, 1])  # 1 = Heads, 0 = Tails
        heads_count += flip
        running_avg.append(heads_count / i)

    return running_avg


def plot_running_average(num_flips):
    running_avg = simulate_flips(num_flips)

    plt.figure(figsize=(10, 6))
    plt.plot(running_avg, color="steelblue", linewidth=1)
    plt.axhline(y=0.5, color="red", linestyle="--", label="Expected (0.5)")

    plt.title(f"Running Average of Heads Proportion over {num_flips} Flips")
    plt.xlabel("Number of Flips")
    plt.ylabel("Proportion of Heads")
    plt.ylim(0, 1)
    plt.legend()
    plt.grid(alpha=0.3)

    plt.show()
    print(f"Final proportion after {num_flips} flips: {running_avg[-1]:.4f}")


plot_running_average(1000)

