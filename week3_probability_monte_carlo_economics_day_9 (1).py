import random
import matplotlib.pyplot as plt
from collections import Counter

shot_pct = 0.70
shots_per_game = 10
num_games = 10000

# Simulate games
makes_per_game = []
for _ in range(num_games):
    makes = sum(1 for _ in range(shots_per_game) if random.random() < shot_pct)
    makes_per_game.append(makes)

# Stats
counts = Counter(makes_per_game)
perfect_games = counts[10]
pct_perfect = perfect_games / num_games * 100

missed_5plus = sum(1 for m in makes_per_game if (shots_per_game - m) >= 5)
pct_missed_5plus = missed_5plus / num_games * 100

print(f"% of games with all 10 made: {pct_perfect:.2f}%")
print(f"% of games missing 5+ shots: {pct_missed_5plus:.2f}%")

# Plot histogram
plt.figure(figsize=(10, 6))
plt.hist(makes_per_game, bins=range(0, 12), align="left", rwidth=0.8,
          color="darkorange", edgecolor="black")
plt.title(f"Histogram of Makes per Game ({num_games} games, {shot_pct*100:.0f}% shooter)")
plt.xlabel("Makes per Game (out of 10)")
plt.ylabel("Number of Games")
plt.xticks(range(0, 11))
plt.grid(alpha=0.3)
plt.show()