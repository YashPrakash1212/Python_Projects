# ==========================================
# RECESSION PREDICTION MODEL
# ==========================================

# Install dependencies:
# pip install pandas numpy scikit-learn matplotlib seaborn
# pip install pandas-datareader requests

import pandas as pd
import numpy as np
import matplotlib.pyplot as plt
import seaborn as sns

from pandas_datareader import data as web

from sklearn.ensemble import RandomForestClassifier
from sklearn.linear_model import LogisticRegression
from sklearn.preprocessing import StandardScaler
from sklearn.pipeline import Pipeline
from sklearn.metrics import (
    accuracy_score,
    precision_score,
    recall_score,
    roc_auc_score,
    classification_report,
    confusion_matrix
)

from sklearn.impute import SimpleImputer

# ==========================================
# 1. DOWNLOAD ECONOMIC DATA FROM FRED
# ==========================================

start_date = "1960-01-01"
end_date = pd.Timestamp.today()

series = {
    "GDP": "A191RL1Q225SBEA",
    "Unemployment": "UNRATE",
    "Interest_Rate": "FEDFUNDS",
    "Inflation": "CPIAUCSL",
    "Recession": "USREC"
}

data = {}

for name, code in series.items():
    data[name] = web.DataReader(
        code,
        "fred",
        start_date,
        end_date
    )

df = pd.concat(data.values(), axis=1)
df.columns = data.keys()

# ==========================================
# 2. TRANSFORM ECONOMIC VARIABLES
# ==========================================

# Convert quarterly GDP growth into monthly data
# using forward fill to align with monthly indicators.

df["GDP"] = df["GDP"].ffill()

# Calculate annual inflation rate
df["Inflation"] = (
    df["Inflation"].pct_change(12) * 100
)

# Unemployment change over three months
df["Unemployment_Change"] = (
    df["Unemployment"] -
    df["Unemployment"].shift(3)
)

# Interest rate changes
df["Interest_Change"] = (
    df["Interest_Rate"] -
    df["Interest_Rate"].shift(3)
)

# GDP momentum
df["GDP_Change"] = (
    df["GDP"] - df["GDP"].shift(1)
)

# ==========================================
# 3. CREATE PREDICTION TARGET
# ==========================================

# Predict whether a recession begins within
# the next three months.

df["Future_Recession"] = (
    df["Recession"]
    .shift(-3)
    .rolling(3)
    .max()
)

df = df.dropna()

# ==========================================
# 4. SELECT FEATURES
# ==========================================

features = [
    "GDP",
    "GDP_Change",
    "Unemployment",
    "Unemployment_Change",
    "Interest_Rate",
    "Interest_Change",
    "Inflation"
]

X = df[features]

y = df["Future_Recession"].astype(int)

# ==========================================
# 5. CHRONOLOGICAL TRAIN/TEST SPLIT
# ==========================================

# Avoid random splitting because this is
# an economic time-series prediction problem.

split = int(len(df) * 0.80)

X_train = X.iloc[:split]
X_test = X.iloc[split:]

y_train = y.iloc[:split]
y_test = y.iloc[split:]

# ==========================================
# 6. RANDOM FOREST MODEL
# ==========================================

rf_model = Pipeline([
    ("imputer", SimpleImputer(strategy="median")),
    ("classifier", RandomForestClassifier(
        n_estimators=500,
        max_depth=6,
        min_samples_leaf=5,
        class_weight="balanced",
        random_state=42
    ))
])

rf_model.fit(X_train, y_train)

# ==========================================
# 7. LOGISTIC REGRESSION MODEL
# ==========================================

lr_model = Pipeline([
    ("imputer", SimpleImputer(strategy="median")),
    ("scaler", StandardScaler()),
    ("classifier", LogisticRegression(
        class_weight="balanced",
        max_iter=2000
    ))
])

lr_model.fit(X_train, y_train)

# ==========================================
# 8. GENERATE PREDICTIONS
# ==========================================

rf_predictions = rf_model.predict(X_test)

rf_probabilities = rf_model.predict_proba(
    X_test
)[:, 1]

lr_probabilities = lr_model.predict_proba(
    X_test
)[:, 1]

# ==========================================
# 9. EVALUATE MODEL PERFORMANCE
# ==========================================

print("\nRANDOM FOREST RESULTS")

print("Accuracy:",
      accuracy_score(y_test, rf_predictions))

print("Precision:",
      precision_score(
          y_test,
          rf_predictions,
          zero_division=0
      ))

print("Recall:",
      recall_score(
          y_test,
          rf_predictions,
          zero_division=0
      ))

print("ROC-AUC:",
      roc_auc_score(y_test, rf_probabilities))

print("\nClassification Report:")

print(classification_report(
    y_test,
    rf_predictions,
    zero_division=0
))

# ==========================================
# 10. FEATURE IMPORTANCE
# ==========================================

forest = rf_model.named_steps["classifier"]

importance = pd.Series(
    forest.feature_importances_,
    index=features
).sort_values(ascending=False)

plt.figure(figsize=(10, 6))

sns.barplot(
    x=importance.values,
    y=importance.index
)

plt.title("Economic Indicators: Feature Importance")
plt.xlabel("Importance")
plt.tight_layout()
plt.show()

# ==========================================
# 11. RECESSION PROBABILITY GRAPH
# ==========================================

plt.figure(figsize=(12, 6))

plt.plot(
    y_test.index,
    rf_probabilities,
    label="Predicted Recession Probability"
)

plt.plot(
    y_test.index,
    y_test.values,
    label="Actual Future Recession",
    alpha=0.5
)

plt.axhline(
    0.5,
    linestyle="--",
    label="50% Probability Threshold"
)

plt.title("Recession Prediction Model")
plt.xlabel("Date")
plt.ylabel("Probability")
plt.legend()
plt.tight_layout()
plt.show()

# ==========================================
# 12. CURRENT RECESSION RISK
# ==========================================

latest_data = df[features].iloc[[-1]]

current_probability = rf_model.predict_proba(
    latest_data
)[0][1]

print("\n================================")
print("CURRENT RECESSION RISK ESTIMATE")
print("================================")

print(
    f"Estimated probability: "
    f"{current_probability * 100:.2f}%"
)

if current_probability >= 0.70:
    print("HIGH RECESSION RISK")

elif current_probability >= 0.40:
    print("MODERATE RECESSION RISK")

else:
    print("LOW RECESSION RISK")