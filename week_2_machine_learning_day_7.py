from sklearn.linear_model import LogisticRegression

#Excercise 1: Creating a pass and a fail dataset, while adding noise.
Study_hours = np.array([5, 6, 7, 8, 1, 2, 3, 4]).reshape(-1,1) #Label
results = [1, 1, 1, 0, 0, 0, 1, 0] #Feature
new_hour = np.array([4.5]).reshape(-1,1)
model = LogisticRegression()
model.fit(Study_hours, results)
predicted_result = model.predict(new_hour)
print(predicted_result)

colors = ['green' if r == 1 else 'red' for r in results]
plt.scatter(Study_hours.flatten(), results, c=colors)