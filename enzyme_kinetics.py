import numpy as np
import matplotlib.pyplot as plt
from scipy.optimize import curve_fit

# ==========================================
# 1. GENERATE EXPERIMENTAL DATA
# ==========================================

np.random.seed(42)

# True enzyme parameters (used to generate test data)
Vmax_true = 100
Km_true = 5

# Substrate concentrations
S = np.linspace(0.5, 50, 30)

# Michaelis-Menten equation
def michaelis_menten(S, Vmax, Km):
    return (Vmax * S) / (Km + S)

# Generate ideal reaction rates
true_rate = michaelis_menten(S, Vmax_true, Km_true)

# Add random experimental noise
noise = np.random.normal(0, 5, len(S))
data_rate = true_rate + noise

# ==========================================
# 2. NONLINEAR OPTIMIZATION
# ==========================================

# Initial guesses for unknown parameters
initial_guess = [80, 3]

# Fit experimental data
parameters, covariance = curve_fit(
    michaelis_menten,
    S,
    data_rate,
    p0=initial_guess,
    bounds=([0, 0], [np.inf, np.inf]),
    maxfev=10000
)

# Extract estimated parameters
Vmax_est, Km_est = parameters

# Estimate parameter standard errors
standard_errors = np.sqrt(np.diag(covariance))

Vmax_error, Km_error = standard_errors

# ==========================================
# 3. GENERATE FITTED CURVE
# ==========================================

S_fit = np.linspace(0, 50, 200)

fitted_rate = michaelis_menten(
    S_fit,
    Vmax_est,
    Km_est
)

# ==========================================
# 4. CALCULATE MODEL ACCURACY
# ==========================================

predicted_rate = michaelis_menten(
    S,
    Vmax_est,
    Km_est
)

residuals = data_rate - predicted_rate

SSE = np.sum(residuals**2)

SST = np.sum((data_rate - np.mean(data_rate))**2)

R_squared = 1 - SSE / SST

RMSE = np.sqrt(np.mean(residuals**2))

# ==========================================
# 5. PRINT RESULTS
# ==========================================

print("\n====================================")
print("MICHAELIS-MENTEN NONLINEAR FIT")
print("====================================")

print("\nTRUE PARAMETERS")
print(f"True Vmax = {Vmax_true:.4f}")
print(f"True Km   = {Km_true:.4f}")

print("\nESTIMATED PARAMETERS")
print(f"Estimated Vmax = {Vmax_est:.4f}")
print(f"Estimated Km   = {Km_est:.4f}")

print("\nPARAMETER STANDARD ERRORS")
print(f"Vmax error = {Vmax_error:.4f}")
print(f"Km error   = {Km_error:.4f}")

print("\nMODEL ACCURACY")
print(f"R-squared = {R_squared:.4f}")
print(f"RMSE      = {RMSE:.4f}")

print("\n====================================")

# ==========================================
# 6. PLOT EXPERIMENTAL DATA AND FIT
# ==========================================

plt.figure(figsize=(10, 6))

# Noisy experimental data
plt.scatter(
    S,
    data_rate,
    color="blue",
    label="Noisy Experimental Data",
    alpha=0.8
)

# True theoretical curve
plt.plot(
    S_fit,
    michaelis_menten(S_fit, Vmax_true, Km_true),
    "g--",
    label="True Michaelis-Menten Curve"
)

# Nonlinear optimized curve
plt.plot(
    S_fit,
    fitted_rate,
    "r-",
    linewidth=2,
    label="Nonlinear Optimized Fit"
)

# Labels and title
plt.xlabel("Substrate Concentration [S]")
plt.ylabel("Reaction Rate")
plt.title("Enzyme Kinetics: Michaelis-Menten Nonlinear Fitting")

plt.legend()
plt.grid(True)

# Save figure
plt.savefig("michaelis_menten_fit.png", dpi=300)

plt.show()

# ==========================================
# 7. DISPLAY ESTIMATED PARAMETERS GRAPHICALLY
