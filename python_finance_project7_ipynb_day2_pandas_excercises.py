student_data_new = {
    "Name": ["Frank", "John", "Anna", "Leo"],
    "Math": [90, 91, 40, 93],
    "Science": [95, 97, 96, 92],
    "English": [85, 78, 92, 88],
    "History": [70, 82, 89, 75],
    "CS": [99, 87, 80, 91],
    "Spanish": [65, 90, 75, 83]
}

df_report = pd.DataFrame(student_data_new)
display(df_report)

import matplotlib.pyplot as plt

# Prepare data for plotting (excluding 'Name' column)
scores_df = df_report.set_index('Name')

# Define colors based on score
def get_bar_colors(score_series):
    return ['green' if score >= 80 else 'red' for score in score_series]

fig, axes = plt.subplots(nrows=len(scores_df), ncols=1, figsize=(10, 3 * len(scores_df)), sharex=True)
fig.suptitle('Student Report Card', fontsize=16, y=0.92)

for i, (student_name, scores) in enumerate(scores_df.iterrows()):
    ax = axes[i]
    colors = get_bar_colors(scores)
    bars = ax.bar(scores.index, scores.values, color=colors)

    ax.set_ylabel(student_name, rotation=0, ha='right', va='center', fontsize=12)
    ax.set_ylim(0, 100) # Set Y-axis limits for scores

    # Add a horizontal dashed line at y=80
    ax.axhline(y=80, color='blue', linestyle='--', linewidth=1, label='Target')

    # Add score values on top of the bars
    for bar in bars:
        yval = bar.get_height()
        ax.text(bar.get_x() + bar.get_width()/2, yval + 2, round(yval, 2), ha='center', va='bottom', fontsize=10)

    # Remove Y-axis ticks and labels for cleaner look, but keep the student name as label
    ax.set_yticks([])

    # Only add legend once
    if i == 0:
        ax.legend(loc='upper right', bbox_to_anchor=(1.15, 1))

plt.xlabel('Subjects', fontsize=12)
plt.xticks(rotation=45, ha='right')
plt.tight_layout(rect=[0, 0.03, 1, 0.88]) # Adjust layout to make space for suptitle
plt.savefig('report_card.png')
plt.show()
print("Report card saved as 'report_card.png'")