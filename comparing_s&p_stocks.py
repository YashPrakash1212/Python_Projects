#Compare 10 stocks against the S&P 500 over the last 5 years.



import yfinance as yf
import pandas as pd
import matplotlib.pyplot as plt
from datetime import datetime, timedelta


# Choose 10 stocks you want to compare
TICKERS = ["AAPL", "MSFT", "GOOGL", "AMZN", "NVDA",
           "META", "TSLA", "JPM", "V", "UNH"]

BENCHMARK = "^GSPC"  # S&P 500 index
YEARS_BACK = 5


end_date = datetime.today()
start_date = end_date - timedelta(days=365 * YEARS_BACK)

all_symbols = TICKERS + [BENCHMARK]

print(f"Downloading {len(all_symbols)} symbols from {start_date.date()} to {end_date.date()}...")

data = yf.download(
    all_symbols,
    start=start_date,
    end=end_date,
    auto_adjust=True,   # adjusts for dividends/splits
    progress=False
)["Close"]

data = data.dropna(how="all").ffill()  # handle occasional missing trading days


normalized = data / data.iloc[0] * 100

# Plot

plt.figure(figsize=(14, 8))

for ticker in TICKERS:
    plt.plot(normalized.index, normalized[ticker], label=ticker, linewidth=1.5, alpha=0.85)

# Plot S&P 500 as a bold black reference line
plt.plot(normalized.index, normalized[BENCHMARK], label="S&P 500",
          color="black", linewidth=2.8)

plt.title(f"Stock Performance vs S&P 500 — Last {YEARS_BACK} Years (Normalized to 100)",
          fontsize=14, fontweight="bold")
plt.xlabel("Date")
plt.ylabel("Normalized Price (Start = 100)")
plt.legend(loc="upper left", ncol=2, fontsize=9)
plt.grid(True, alpha=0.3)
plt.tight_layout()

output_path = "stock_vs_sp500.png"
plt.savefig(output_path, dpi=150)
print(f"Chart saved to {output_path}")
plt.show()

# ---- Summary table: total return over the period -------------------------

total_return = (normalized.iloc[-1] - 100).sort_values(ascending=False)
print("\nTotal return over the period (%):")
print(total_return.round(2))