#Excercise 1: Estimating pi with random darts
import numpy as np

n = 10000

# Generate random points in unit square [0,1] x [0,1]
x = np.random.uniform(0, 1, n)
y = np.random.uniform(0, 1, n)

# Count points inside quarter-circle (x^2 + y^2 < 1)
inside = (x**2 + y**2) < 1
n_inside = np.sum(inside)

# Estimate pi
pi_estimate = 4 * (n_inside / n)

print(f"Points inside quarter-circle: {n_inside} out of {n}")
print(f"Estimated pi: {pi_estimate}")
print(f"Actual pi:    {np.pi}")
print(f"Error: {abs(pi_estimate - np.pi):.5f}")

#Exercise 2: Visualize the darts
import numpy as np
import matplotlib.pyplot as plt

n = 10000

x = np.random.uniform(0, 1, n)
y = np.random.uniform(0, 1, n)

inside = (x**2 + y**2) < 1
pi_estimate = 4 * (np.sum(inside) / n)

fig, ax = plt.subplots(figsize=(7,7))
ax.scatter(x[inside], y[inside], color='red', s=3, label='Inside circle')
ax.scatter(x[~inside], y[~inside], color='blue', s=3, label='Outside circle')

# quarter-circle arc
theta = np.linspace(0, np.pi/2, 200)
ax.plot(np.cos(theta), np.sin(theta), color='black', linewidth=2)

ax.set_aspect('equal')
ax.set_title("Estimating Pi with Monte Carlo (n=10000)")
ax.legend(loc='upper right', markerscale=4)
plt.show()

#Excercise 3: Convergence Plot
import numpy as np
import matplotlib.pyplot as plt

sample_sizes = [10, 100, 1000, 10000, 100000]
estimates = []

for n in sample_sizes:
    x = np.random.uniform(0, 1, n)
    y = np.random.uniform(0, 1, n)
    inside = (x**2 + y**2) < 1
    pi_estimate = 4 * (np.sum(inside) / n)
    estimates.append(pi_estimate)

fig, ax = plt.subplots(figsize=(9,5))
ax.plot(sample_sizes, estimates, marker='o', linewidth=2, label='Pi estimate')
ax.axhline(np.pi, color='red', linestyle='--', linewidth=2, label=f'Actual pi = {np.pi:.5f}')
ax.set_xscale('log')
ax.set_xlabel("Number of points (log scale)")
ax.set_ylabel("Pi estimate")
ax.set_title("Monte Carlo Pi Estimate Converging as Sample Size Grows")
ax.legend()
ax.grid(True, alpha=0.3)
plt.show()

