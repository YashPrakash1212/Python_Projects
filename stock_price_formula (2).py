import numpy as np
import matplotlib.pyplot as plt

# ==================================
# 1. MODEL PARAMETERS
# ==================================

S0 = 100          # Initial stock price ($)
mu = 0.08         # Expected annual return (8%)
sigma = 0.20      # Annual volatility (20%)

T = 1             # Simulation period (1 year)
N = 252           # Trading days per year
M = 100           # Number of simulated paths

dt = T / N

# Reproducible random numbers
np.random.seed(42)

# ==================================
# 2. GENERATE BROWNIAN MOTION
# ==================================

Z = np.random.normal(0, 1, (M, N))

# ==================================
# 3. STOCK PRICE SIMULATION
# ==================================

S = np.zeros((M, N + 1))

# Initial stock price
S[:, 0] = S0

# GBM stochastic differential equation:
#
# dS = mu*S*dt + sigma*S*dW
#
# Exact discrete-time solution:

for t in range(N):

    S[:, t+1] = S[:, t] * np.exp(
        (mu - 0.5 * sigma**2) * dt
        + sigma * np.sqrt(dt) * Z[:, t]
    )

# ==================================
# 4. TIME ARRAY
# ==================================

time = np.linspace(0, T, N + 1)

# ==================================
# 5. PLOT STOCK PRICE PATHS
# ==================================

plt.figure(figsize=(12, 6))

for i in range(M):
    plt.plot(time, S[i, :], alpha=0.25)

plt.title("Stock Price Simulation Using GBM")
plt.xlabel("Time (Years)")
plt.ylabel("Stock Price ($)")
plt.grid(True)

plt.show()

# ==================================
# 6. EXPECTED STOCK PRICE
# ==================================

expected_price = S0 * np.exp(mu * T)

# Monte Carlo average final price
average_price = np.mean(S[:, -1])

print("--------------------------------")
print("STOCK PRICE SIMULATION RESULTS")
print("--------------------------------")

print("Initial Stock Price:", S0)
print("Expected Theoretical Price:", round(expected_price, 2))
print("Average Simulated Final Price:", round(average_price, 2))
print("Minimum Simulated Price:", round(np.min(S[:, -1]), 2))
print("Maximum Simulated Price:", round(np.max(S[:, -1]), 2))
print("--------------------------------")