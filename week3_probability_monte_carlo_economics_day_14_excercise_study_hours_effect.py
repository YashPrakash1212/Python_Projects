#Monte Carlo Investment Simulator


import numpy as np
import matplotlib.pyplot as plt
import yfinance as yf

# ----------------------------------------------------------------------
# PART 1: INPUT
# ----------------------------------------------------------------------
TICKER = "AAPL"
INVESTMENT = 10000       # dollars
HORIZON_MONTHS = 12      # months

# Part 2: Historical analysis

def get_historical_stats(ticker, period="2y"):
    data = yf.download(ticker, period=period, progress=False)
    returns = data['Close'].pct_change().dropna()
    mu = float(returns.mean())
    sigma = float(returns.std())
    return mu, sigma

mu, sigma = get_historical_stats(TICKER)

print(f"Based on historical data, {TICKER} has avg daily return of {mu*100:.2f}% "
      f"and volatility of {sigma*100:.2f}%\n")

# Part 3: Simulation

TRADING_DAYS_PER_MONTH = 21
n_days = HORIZON_MONTHS * TRADING_DAYS_PER_MONTH
n_sims = 10000

Z = np.random.standard_normal((n_days, n_sims))
daily_growth = np.exp((mu - 0.5 * sigma**2) + sigma * Z)

paths = np.zeros((n_days + 1, n_sims))
paths[0] = INVESTMENT
paths[1:] = INVESTMENT * np.cumprod(daily_growth, axis=0)

final_values = paths[-1]

# Part 4: Visualization

fig, (ax1, ax2) = plt.subplots(2, 1, figsize=(11, 10))

sample_idx = np.random.choice(n_sims, size=100, replace=False)
ax1.plot(paths[:, sample_idx], color='steelblue', linewidth=0.7, alpha=0.5)
ax1.axhline(INVESTMENT, color='black', linestyle='--', linewidth=1.5,
            label=f'Initial investment = ${INVESTMENT:,.0f}')
ax1.plot(paths.mean(axis=1), color='red', linewidth=2, label='Mean path')
ax1.set_title(f"{TICKER}: 100 Sample Simulated Paths ({HORIZON_MONTHS} months, {n_sims:,} total sims)")
ax1.set_xlabel("Trading day")
ax1.set_ylabel("Portfolio value ($)")
ax1.legend()
ax1.grid(True, alpha=0.3)

ax2.hist(final_values, bins=60, color='seagreen', edgecolor='black', alpha=0.75)
ax2.axvline(INVESTMENT, color='black', linestyle='--', linewidth=1.5,
            label=f'Initial investment = ${INVESTMENT:,.0f}')
ax2.axvline(final_values.mean(), color='red', linewidth=2,
            label=f'Mean final value = ${final_values.mean():,.0f}')
ax2.set_title(f"Distribution of Final Portfolio Values ({n_sims:,} simulations)")
ax2.set_xlabel("Final portfolio value ($)")
ax2.set_ylabel("Frequency")
ax2.legend()
ax2.grid(True, alpha=0.3)

plt.tight_layout()
plt.show()